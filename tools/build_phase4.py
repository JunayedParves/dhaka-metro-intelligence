def fk_target(table, col):
    for suffix, dim, dcol in FK_RULES:
        if col.endswith(suffix) and table != dim:
            return dim, dcol
    return None


def infer(vals):
    nn = [str(v) for v in vals if v not in ("", None)]
    nullable = len(nn) < len(vals)
    if not nn:
        return "NVARCHAR(50)", True
    if all(re.fullmatch(r"-?\d+", v) for v in nn):
        big = max(abs(int(v)) for v in nn) > 2_000_000_000
        return ("BIGINT" if big else "INT"), nullable
    if all(re.fullmatch(r"-?\d+(\.\d+)?([eE][-+]?\d+)?", v) for v in nn):
        return "DECIMAL(20,4)", nullable
    if all(re.fullmatch(r"\d{4}-\d{2}-\d{2}", v) for v in nn):
        return "DATE", nullable
    if all(re.fullmatch(r"\d{2}:\d{2}", v) for v in nn):
        return "TIME(0)", nullable
    n = max(len(v) for v in nn)
    size = next(s for s in (10, 20, 50, 100, 200, 400, 1000, 4000) if s >= n) if n <= 4000 else "MAX"
    return f"NVARCHAR({size})", nullable


