def read(path):
    with open(path, encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


TABLES = OrderedDict()     # name -> dict(cols, rows, pk, grain, desc)


def add(name, cols, rows, pk, grain, desc):
    with open(D_STAR / f"{name}.csv", "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(cols)
        w.writerows(rows)
    TABLES[name] = dict(cols=cols, rows=rows, pk=pk, grain=grain, desc=desc)


def dkey(s):
    return int(s[:10].replace("-", "")) if s and re.match(r"\d{4}-\d{2}-\d{2}", s) else None


def fy_start_key(fy):
    return int(fy[:4]) * 10000 + 701


def fy_of(d):
    return f"{d.year}-{str(d.year + 1)[2:]}" if d.month >= 7 else f"{d.year - 1}-{str(d.year)[2:]}"


