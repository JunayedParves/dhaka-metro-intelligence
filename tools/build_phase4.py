# ====================================================================== facts
PROV = ["Classification_Key", "Source_Key", "Source_ID", "Data_Confidence", "Is_Modelled", "Is_Verified"]
UNRESOLVED = defaultdict(int)


def prov(r):
    dt = r["Data_Type"]
    sid = re.split(r"[;]", r["Source_ID"])[0].strip()
    if sid not in SRC:
        UNRESOLVED[sid] += 1
    return [CLASS[dt], SRC.get(sid, 0), r["Source_ID"], r["Data_Confidence"], 1 if r["Is_Modelled"] == "Yes" else 0, 1 if r["Is_Verified"] == "Yes" else 0]


def num(v):
    return v if v not in ("", None) else ""


def fact(name, src, cols, fn, pk, grain, desc):
    rows = []
    for r in read(src):
        out = fn(r)
        if out is not None:
            rows.append(out + prov(r))
    add(name, cols + PROV, rows, pk, grain, desc)


